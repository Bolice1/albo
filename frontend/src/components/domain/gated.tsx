"use client";

import { Skeleton, StateBlock } from "@/components/domain";
import { ButtonLink } from "@/components/ui/primitives";
import { useFeatures } from "@/lib/api/hooks";
import type { CrisisEscalationCard, FeatureFlags } from "@/lib/api/types";
import { cn } from "@/lib/format";
import { FlaskConical, LifeBuoy, MapPin, Phone } from "lucide-react";

/** Marks a screen as a gated preview (ADR-017, ADR-019). */
export function PreviewBanner({ children, phase = "gated" }: { children?: React.ReactNode; phase?: "gated" | "later" }) {
  return (
    <div className="flex items-start gap-3 rounded-2xl border border-accent-200 bg-accent-50 px-4 py-3 text-sm">
      <FlaskConical className="mt-0.5 size-4 shrink-0 text-accent-600" aria-hidden />
      <p className="text-ink-soft">
        <span className="font-medium text-ink">{phase === "later" ? "Later-phase preview." : "Preview feature."}</span>{" "}
        {children ??
          (phase === "later"
            ? "This shows a planned capability using synthetic data. It isn't available yet."
            : "Available for testing with synthetic data. It stays off for real users until its safety and approval steps are complete.")}
      </p>
    </div>
  );
}

/** Renders children only when the runtime gate is on; otherwise a safe unavailable state. */
export function FeatureGate({ flag, name, children }: { flag: keyof FeatureFlags; name: string; children: React.ReactNode }) {
  const { data, isLoading } = useFeatures();
  if (isLoading) return <Skeleton className="h-64" />;
  if (!data?.[flag]) {
    return (
      <StateBlock
        kind="unavailable"
        title={`${name} isn't available yet`}
        description="This feature is switched off. It will appear once it's approved."
        action={<ButtonLink href="/dashboard" variant="secondary" size="sm">Back to dashboard</ButtonLink>}
        className="rounded-[var(--radius-card)] bg-surface/85 py-16"
      />
    );
  }
  return <>{children}</>;
}

/** Deterministic escalation card (FR-024). Never generated by a model. */
export function CrisisCard({ card, className }: { card: CrisisEscalationCard; className?: string }) {
  return (
    <section
      role="alert"
      aria-labelledby="crisis-headline"
      className={cn("rounded-[var(--radius-card)] border-2 border-high/30 bg-high-bg p-5", className)}
    >
      <h2 id="crisis-headline" className="flex items-center gap-2 text-lg font-semibold text-ink">
        <LifeBuoy className="size-5 text-high" aria-hidden /> {card.headline}
      </h2>
      <p className="mt-2 text-sm text-ink-soft">{card.message}</p>

      <ul className="mt-4 space-y-2">
        {card.emergency_contacts.map((c) => (
          <li key={c.code} className="flex items-center gap-3 rounded-xl bg-surface px-4 py-3">
            <Phone className="size-4 shrink-0 text-high" aria-hidden />
            <div className="min-w-0">
              <p className="text-sm font-medium">{c.label}</p>
              <p className="text-xs text-muted">{c.contact_reference}</p>
            </div>
          </li>
        ))}
      </ul>

      {card.verified_facilities.length > 0 && (
        <>
          <p className="mt-4 text-xs font-medium uppercase tracking-wide text-muted">Nearby care</p>
          <ul className="mt-2 grid gap-2 sm:grid-cols-2">
            {card.verified_facilities.map((f) => (
              <li key={f.id} className="flex items-start gap-3 rounded-xl bg-surface px-4 py-3">
                <MapPin className="mt-0.5 size-4 shrink-0 text-accent-600" aria-hidden />
                <div className="min-w-0">
                  <p className="text-sm font-medium">{f.name}</p>
                  <p className="text-xs text-muted">{f.address}</p>
                  {f.contact && <p className="text-xs text-muted">{f.contact}</p>}
                </div>
              </li>
            ))}
          </ul>
        </>
      )}
      <p className="mt-4 text-[11px] text-muted">{card.governance_notice}</p>
    </section>
  );
}
